CREATE DATABASE CIS_DB;

USE CIS_DB;

CREATE TABLE cis_rules(
rule_id INT  AUTO_INCREMENT PRIMARY KEY,
cis_id VARCHAR(20) NOT NULL,
title VARCHAR(255) NOT NULL,
platform VARCHAR(50) NOT NULL,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
is_active BOOLEAN NOT NULL DEFAULT TRUE,
updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
UNIQUE KEY 	uq_cis_rule(cis_id, platform)
);


CREATE TABLE cis_commands(
command_id INT AUTO_INCREMENT PRIMARY KEY,
rule_id INT NOT NULL,
command_type VARCHAR(20) NOT NULL,
step_order INT NOT NULL DEFAULT 1,
command TEXT NOT NULL,
expected_result TEXT NULL,
match_type VARCHAR(20) NULL,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

CONSTRAINT fk_commands_rule
   FOREIGN KEY (rule_id) REFERENCES cis_rules(rule_id)
   ON DELETE CASCADE,

INDEX idx_rule_type_step(rule_id, command_type, step_order)
);
   
